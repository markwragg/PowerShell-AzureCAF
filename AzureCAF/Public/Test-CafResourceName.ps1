function Test-CafResourceName {
    <#
    .SYNOPSIS
        Tests whether a name complies with the Cloud Adoption Framework naming rules for an Azure
        resource type.
    .DESCRIPTION
        Checks a resource name against the same rules Get-CafResourceName enforces when building one:
        minimum/maximum length, required casing, whether the resource type allows a dash, and the
        overall set of valid characters. Returns an object showing the pass/fail result of each rule, a
        plain-English Reason when it's invalid, and an overall IsValid result - or just the overall
        true/false with -Quiet.

        IsValid is the authoritative result (the same validation pattern Get-CafResourceName itself checks
        names against); the other fields are a diagnostic breakdown to help pinpoint why a name failed.
        For a small number of resource types the breakdown can't perfectly add up to IsValid - for
        example a character that's only disallowed as the *first* character of a name is flagged as
        invalid by -ValidCharacters wherever it appears, even though IsValid may still be true if it
        appears elsewhere. Treat IsValid as the source of truth.
    .PARAMETER Name
        The resource name to test, e.g. 'contoso-prod-vm-001'.
    .PARAMETER ResourceType
        The ARM resource type to test the name against, e.g. 'Microsoft.Compute/virtualMachines'.
        Matches as a substring by default. Normally used on its own (or -Alias, or -Resource, used
        instead); takes precedence if more than one happens to be specified, e.g. by piping in an
        object that has ResourceType, Alias and Resource properties all describing the same entry.
    .PARAMETER Alias
        The Cloud Adoption Framework abbreviation to test the name against, e.g. 'vmss', used as a
        short alias for the ARM resource type. Matches as a substring by default, and also accepts
        -Slug as an alias. Normally used on its own, instead of -ResourceType.
    .PARAMETER Resource
        The friendly name of the resource to test against, e.g. 'Key vault' - every such name in the
        module's data is unique, so on its own this works as a third alternative to -ResourceType/
        -Alias (also matching as a substring). It also doubles as a disambiguator when combined with
        -ResourceType/-Alias, for the handful of ARM types used by more than one kind of resource (for
        example 'Microsoft.Web/sites' covers both a "Web app" and a "Function app") - required in that
        case, since -ResourceType/-Alias alone would otherwise be ambiguous.
    .PARAMETER Quiet
        Return only an overall $true/$false instead of the full breakdown object.
    .EXAMPLE
        Test-CafResourceName -Name 'contoso-prod-vm-001' -ResourceType Microsoft.Compute/virtualMachines

        Returns an object showing which naming rules the name passes or fails, and an overall IsValid.
    .EXAMPLE
        (Test-CafResourceName -Name 'CONTOSO' -ResourceType Microsoft.Storage/storageAccounts).Reason

        Returns 'Name must be all lowercase for this resource type.' - Reason explains an invalid
        result in plain English; it's $null when IsValid is $true.
    .EXAMPLE
        Test-CafResourceName -Name 'Contoso_VM!' -Alias vm -Quiet

        Returns $false - the name is uppercase, contains an underscore and an exclamation mark, none of
        which are valid for a virtual machine name.
    .EXAMPLE
        Test-CafResourceName -Name 'contoso-kv' -Resource 'Key vault'

        -Resource alone works too, since every friendly name is unique - a third alternative to
        -ResourceType/-Alias for when you only remember the resource's plain-English name.
    .EXAMPLE
        Get-CafResourceName -ResourceType Microsoft.Storage/storageAccounts -Prefix contoso -RandomSuffixLength 6 |
            Test-CafResourceName -ResourceType Microsoft.Storage/storageAccounts -Quiet

        Round-trips a name generated by Get-CafResourceName back through Test-CafResourceName.
    .LINK
        https://learn.microsoft.com/en-us/azure/cloud-adoption-framework/ready/azure-best-practices/resource-abbreviations
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory, Position = 0, ValueFromPipeline)]
        [ValidateNotNullOrEmpty()]
        [string]
        $Name,

        [Parameter(Position = 1, ValueFromPipelineByPropertyName)]
        [ValidateNotNullOrEmpty()]
        [string]
        $ResourceType,

        [Parameter(ValueFromPipelineByPropertyName)]
        [Alias('Slug')]
        [ValidateNotNullOrEmpty()]
        [string]
        $Alias,

        [Parameter(ValueFromPipelineByPropertyName)]
        [ValidateNotNullOrEmpty()]
        [string]
        $Resource,

        [switch]
        $Quiet
    )

    process {
        if (-not $ResourceType -and -not $Alias -and -not $Resource) {
            Write-Error 'Specify -ResourceType, -Alias or -Resource to identify the resource type.'
            return
        }

        $definition = Resolve-CafResourceDefinition -ResourceType $ResourceType -Alias $Alias -Resource $Resource

        if (-not $definition) {
            return
        }

        $MinLength = $Name.Length -ge $definition.MinLength
        $MaxLength = $Name.Length -le $definition.MaxLength
        $Casing = -not ($definition.Lowercase -and $Name -cmatch '[A-Z]')
        $Dashes = $definition.Dashes -or $Name -cnotmatch '-'
        $ValidCharacters = $Name -cnotmatch $definition.InvalidCharsRegex
        $IsValid = $Name -cmatch $definition.ValidationRegex

        if ($Quiet) {
            return $IsValid
        }

        $Reasons = [System.Collections.Generic.List[string]]::new()

        if ($IsValid) {
            # Even if every breakdown field is individually true, IsValid is the authoritative check -
            # there's nothing to explain when it passed, regardless of what the breakdown says.
        }
        else {
            if (-not $MinLength) {
                $Reasons.Add("Name is $($Name.Length) character$(if ($Name.Length -ne 1) { 's' }), which is shorter than the $($definition.MinLength) character minimum.")
            }

            if (-not $MaxLength) {
                $Reasons.Add("Name is $($Name.Length) characters, which exceeds the $($definition.MaxLength) character maximum by $($Name.Length - $definition.MaxLength).")
            }

            if (-not $Casing) {
                $Reasons.Add('Name must be all lowercase for this resource type.')
            }

            if (-not $Dashes) {
                $Reasons.Add("Name contains a dash ('-'), which this resource type does not allow.")
            }

            if (-not $ValidCharacters) {
                $Reasons.Add('Name contains characters that are not allowed for this resource type.')
            }

            if ($Reasons.Count -eq 0) {
                # None of the simple per-rule checks explain it - some resource types have additional
                # positional rules (e.g. must start/end with a letter) that aren't broken out above.
                $Reasons.Add("Name does not match the required pattern for this resource type (pattern: $($definition.ValidationRegex)).")
            }
        }

        [pscustomobject]@{
            Name            = $Name
            ResourceType    = $definition.ResourceType
            Resource        = $definition.Resource
            IsValid         = $IsValid
            Reason          = if ($Reasons.Count -gt 0) { $Reasons -join ' ' } else { $null }
            MinLength       = $MinLength
            MaxLength       = $MaxLength
            Casing          = $Casing
            Dashes          = $Dashes
            ValidCharacters = $ValidCharacters
        }
    }
}
